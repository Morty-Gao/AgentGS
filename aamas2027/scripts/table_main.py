#!/usr/bin/env python3
"""Generate the GeoToolEval main-table layout with explicit numeric placeholders.

Run from the paper directory with ``uv run --offline --no-sync python scripts/table_main.py``.
"""

from __future__ import annotations

import argparse
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / "tables" / "main_results.tex"
PLACEHOLDER = "0.0000"
GROUPS = (
    ("Bash-only agents", ("DeepSeek V4.1 Flash", "GPT-5.6 Terra"), False),
    (
        "AgentGS",
        (
            "Qwen3.5-4B",
            "Qwen3.5-9B",
            "Qwen3.5-35B-A3B",
            "Qwen3.8-27B",
            "Qwen3.8-Plus",
            "GeoGPT-Qwen2.5-72B",
            "DeepSeek V4.1 Flash",
            "GPT-5.6 Terra",
        ),
        True,
    ),
)


def render() -> str:
    lines = [
        "% Generated by scripts/table_main.py; numeric entries are placeholders.",
        r"\begin{table*}[!t]",
        r"\caption{GeoToolEval results. All numeric entries are placeholders. "
        r"Quality is the weighted aggregate in Appendix~\ref{app:metric-details}. "
        r"Bash-only agents investigate data through shell commands; "
        r"Quality and tool-chain metrics are not applicable (---).}",
        r"\label{tab:main-results}",
        r"\centering",
        r"\begin{tabularx}{\textwidth}{@{}X*{6}{>{\centering\arraybackslash}p{0.09\textwidth}}@{}}",
        r"\toprule",
        r"Model & Quality $\uparrow$ & FAS $\uparrow$ & TSF1 $\uparrow$ "
        r"& PAS $\uparrow$ & TOS $\uparrow$ & ECR $\uparrow$ \\",
    ]
    for title, models, has_tool_metrics in GROUPS:
        lines.extend((r"\midrule", rf"\multicolumn{{7}}{{@{{}}l}}{{\textbf{{{title}}}}} \\"))
        for model in models:
            tool_scores = [PLACEHOLDER] * 5 if has_tool_metrics else ["---"] * 5
            scores = [tool_scores[0], PLACEHOLDER, *tool_scores[1:]]
            lines.append(model + " & " + " & ".join(scores) + r" \\")
    lines.extend((r"\bottomrule", r"\end{tabularx}", r"\end{table*}", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=OUTPUT, help="Output LaTeX file")
    output = parser.parse_args().output
    content = render()
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
