"""Generate TypeScript response types from Pydantic serialization contracts."""

import json
from pathlib import Path

from agentgs.contracts.models import Event, TaskInput, TaskRecord, ToolSpec
from agentgs.messages import Conversation
from agentgs.skills.base import SkillSpec
from agentgs.visualization.backend.models import ConsoleConfig, TaskPage


def type_expression(schema):
    if "const" in schema:
        return json.dumps(schema["const"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(type_expression(s) for s in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "array":
        return f"Array<{type_expression(schema['items'])}>"
    if kind == "object":
        if "properties" not in schema:
            value = schema.get("additionalProperties", {})
            return f"Record<string, {type_expression(value) if isinstance(value, dict) else 'unknown'}>"
        required = set(schema.get("required", []))
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(name)}{'' if name in required else '?'}: {type_expression(prop)}"
                for name, prop in schema["properties"].items()
            )
            + " }"
        )
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}.get(
        kind, "unknown"
    )


def main():
    root = next(p for p in Path(__file__).resolve().parents if (p / "pyproject.toml").exists())
    definitions = {}
    for model in [Event, TaskRecord, ToolSpec, SkillSpec, Conversation, TaskPage, ConsoleConfig]:
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema

    # Request defaults are optional; response defaults are always serialized.
    def request_names(value):
        if isinstance(value, list):
            return [request_names(item) for item in value]
        if not isinstance(value, dict):
            return value
        return {
            key: "#/$defs/Input" + item.rsplit("/", 1)[-1] if key == "$ref" else request_names(item)
            for key, item in value.items()
        }

    schema = TaskInput.model_json_schema(mode="validation")
    for name, definition in schema.pop("$defs", {}).items():
        definitions["Input" + name] = request_names(definition)
    definitions["TaskSubmission"] = request_names(schema)
    path = root / "src/agentgs/visualization/frontend/src/contracts.ts"
    path.write_text(
        "// Generated by scripts/build/build_api_types.py; do not edit.\n"
        + "\n".join(
            f"export type {name} = {type_expression(schema)};"
            for name, schema in definitions.items()
        )
        + "\n"
    )
    print(path)


if __name__ == "__main__":
    main()
